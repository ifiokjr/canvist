/// Generates `lib/src/extensions.g.dart`: a typed handle class per
/// extension, from the extension metadata `canvist_extensions` snapshots in
/// its tests. The Rust commands check their arguments against the same
/// metadata, so the Dart signatures cannot drift from them. The StarterKit
/// snapshot says which extensions make up [Engine.starterKit].
///
/// ```sh
/// dart run tool/generate.dart          # write the file
/// dart run tool/generate.dart --check  # fail if it is out of date
/// ```
library;

import 'dart:convert';
import 'dart:io';

const _snapshots = '../../crates/canvist_extensions/tests/snapshots';
final _everySnapshot = File(
  '$_snapshots/extensions_api__extension_metadata.snap',
);
final _starterKitSnapshot = File('$_snapshots/api__starter_kit_metadata.snap');
final _output = File('lib/src/extensions.g.dart');

/// Extensions every engine registers; only paragraphs have commands.
const _core = {'doc', 'paragraph', 'baseKeymap', 'undoInputRule'};

typedef _Json = Map<String, Object?>;

Future<void> main(List<String> arguments) async {
  final extensions = await _read(_everySnapshot)
    ..sort((a, b) => _name(a).compareTo(_name(b)));
  final starterKit = {
    for (final e in await _read(_starterKitSnapshot)) _name(e),
  };
  final generated = await _format(_render(extensions, starterKit));

  if (!arguments.contains('--check')) {
    await _output.writeAsString(generated);
    return;
  }

  if (await _output.readAsString() != generated) {
    stderr.writeln('$_output is out of date; run dart run tool/generate.dart');
    exitCode = 1;
  }
}

/// The extensions in an insta snapshot: its JSON body after the header.
Future<List<_Json>> _read(File snapshot) async {
  final body = (await snapshot.readAsString()).replaceFirst(
    RegExp(r'^---\n[\s\S]*?\n---\n'),
    '',
  );

  return (jsonDecode(body) as List<Object?>).cast<_Json>();
}

String _name(_Json extension) => extension['name']! as String;

String _pascal(String name) => name[0].toUpperCase() + name.substring(1);

List<_Json> _list(_Json json, String key) =>
    (json[key]! as List<Object?>).cast<_Json>();

String _render(List<_Json> extensions, Set<String> starterKitNames) {
  final optional = extensions.where((e) => !_core.contains(_name(e))).toList();
  final starterKit = optional
      .where((e) => starterKitNames.contains(_name(e)))
      .toList();
  final withHandles = extensions.where(
    (e) => !_core.contains(_name(e)) || _name(e) == 'paragraph',
  );
  final out = StringBuffer()
    ..writeln('// Generated by tool/generate.dart from the metadata snapshot.')
    ..writeln('// Do not edit.')
    ..writeln()
    ..writeln("part of 'engine.dart';")
    ..writeln();

  for (final extension in withHandles) {
    _handle(out, extension);
  }

  for (final extension in optional) {
    final pascal = _pascal(_name(extension));
    out
      ..writeln('/// Registers `${_name(extension)}`.')
      ..writeln(
        'final class ${pascal}Extension extends Extension<${pascal}Handle> {',
      )
      ..writeln(
        "  const ${pascal}Extension._() : super('${_name(extension)}');",
      )
      ..writeln('  @override')
      ..writeln(
        '  ${pascal}Handle _handle(Registration registration) => ${pascal}Handle._(registration);',
      )
      ..writeln('}')
      ..writeln();
  }

  out
    ..writeln('/// Every extension, to pass to [EngineBuilder.add].')
    ..writeln('abstract final class Extensions {');

  for (final extension in optional) {
    out
      ..writeln('  /// The `${_name(extension)}` extension.')
      ..writeln(
        '  static const ${_name(extension)} = ${_pascal(_name(extension))}Extension._();',
      );
  }

  out
    ..writeln()
    ..writeln("  /// TipTap's StarterKit, which [Engine.starterKit] registers.")
    ..writeln('  static const starterKit = <Extension<ExtensionHandle>>[')
    ..writeln(starterKit.map((e) => '    ${_name(e)},').join('\n'))
    ..writeln('  ];')
    ..writeln()
    ..writeln('  /// Every extension above.')
    ..writeln('  static const all = <Extension<ExtensionHandle>>[')
    ..writeln(optional.map((e) => '    ${_name(e)},').join('\n'))
    ..writeln('  ];')
    ..writeln('}')
    ..writeln()
    ..writeln(
      '/// Handles for every StarterKit extension, from [Engine.starterKit].',
    )
    ..writeln('final class StarterKitHandles {')
    ..writeln('  StarterKitHandles._(EngineBuilder builder)')
    ..write('    : paragraph = builder.paragraph');

  for (final extension in starterKit) {
    out.write(
      ',\n      ${_name(extension)} = builder.add(Extensions.${_name(extension)})',
    );
  }

  out
    ..writeln(';')
    ..writeln()
    ..writeln('  /// Paragraphs.')
    ..writeln('  final ParagraphHandle paragraph;');

  for (final extension in starterKit) {
    out
      ..writeln('  /// `${_name(extension)}`.')
      ..writeln(
        '  final ${_pascal(_name(extension))}Handle ${_name(extension)};',
      );
  }

  return (out..writeln('}')).toString();
}

void _handle(StringBuffer out, _Json extension) {
  final pascal = _pascal(_name(extension));
  out
    ..writeln('/// The commands and queries of `${_name(extension)}`.')
    ..writeln('final class ${pascal}Handle extends ExtensionHandle {')
    ..writeln('  ${pascal}Handle._(super.registration) : super._();')
    ..writeln();

  for (final command in _list(extension, 'commands')) {
    final args = _list(command, 'args');
    out
      ..writeln(_doc(command, args))
      ..writeln('  Command ${command['name']}(${_params(args)}) =>')
      ..writeln("      _command('${command['name']}', ${_argsMap(args)});")
      ..writeln();
  }

  for (final query in _list(extension, 'queries')) {
    final returns = query['returns']! as _Json;
    final args = _list(query, 'args');
    final passed = args.isEmpty ? '' : ', ${_argsMap(args)}';
    out
      ..writeln(_doc(query, args))
      ..writeln(
        '  Query<${_dartType(returns)}> ${query['name']}(${_params(args)}) =>',
      )
      ..writeln(
        "      _query('${query['name']}', (json) => ${_decode(returns, 'json')}$passed);",
      )
      ..writeln();
  }

  out
    ..writeln('}')
    ..writeln();
}

String _doc(_Json item, List<_Json> args) {
  final lines = ['  /// ${item['doc']}'];

  for (final arg in args) {
    lines.add('  ///');
    lines.add(
      '  /// [${arg['name']}]: ${arg['doc']}${_range(arg['type']! as _Json)}',
    );
  }

  return lines.join('\n');
}

String _range(_Json type) => type.containsKey('min')
    ? ' From ${type['min']} to ${type['max']}.'
    : type.containsKey('enum')
    ? ' One of ${(type['enum']! as List<Object?>).join(', ')}.'
    : '';

String _params(List<_Json> args) {
  if (args.isEmpty) {
    return '';
  }

  for (final arg in args) {
    if ((arg['type']! as _Json)['type'] == 'record') {
      throw FormatException(
        'record arguments are not supported: ${arg['name']}',
      );
    }
  }

  final params = args.map((arg) {
    final type = _dartType(arg['type']! as _Json);
    final optional = arg.containsKey('default');
    final nullable = type.endsWith('?') ? type : '$type?';

    return optional
        ? '$nullable ${arg['name']}'
        : 'required $type ${arg['name']}';
  });

  return '{${params.join(', ')}}';
}

String _argsMap(List<_Json> args) {
  if (args.isEmpty) {
    return 'const {}';
  }

  final entries = args.map(
    (arg) => arg.containsKey('default')
        ? "'${arg['name']}': ?${arg['name']}"
        : "'${arg['name']}': ${arg['name']}",
  );

  return '{${entries.join(', ')}}';
}

String _dartType(_Json type) => switch (type['type']) {
  'bool' => 'bool',
  'int' => 'int',
  'float' => 'double',
  'string' => 'String',
  'nullable' => '${_dartType(type['of']! as _Json)}?',
  'list' => 'List<${_dartType(type['of']! as _Json)}>',
  'record' => '({${_list(type, 'fields').map(_recordField).join(', ')}})',
  final other => throw FormatException('unknown value type $other'),
};

/// One named field of a Dart record type.
String _recordField(_Json field) =>
    '${_dartType(field['type']! as _Json)} ${field['name']}';

/// An expression decoding [value]; `[value]!` unless a null check already
/// promoted it. [depth] keeps the names nested lists and records bind
/// apart.
String _decode(
  _Json type,
  String value, {
  bool promoted = false,
  int depth = 0,
}) {
  final known = promoted ? value : '$value!';

  return switch (type['type']) {
    'bool' => '$known as bool',
    'int' => '($known as num).toInt()',
    'float' => '($known as num).toDouble()',
    'string' => '$known as String',
    'nullable' =>
      '$value == null ? null : ${_decode(type['of']! as _Json, value, promoted: true, depth: depth)}',
    'list' => _decodeList(type, known, depth),
    'record' => _decodeRecord(type, known, depth),
    final other => throw FormatException('unknown value type $other'),
  };
}

String _decodeList(_Json type, String known, int depth) {
  final item = 'item$depth';
  final decoded = _decode(type['of']! as _Json, item, depth: depth + 1);

  return '[for (final $item in $known as List<Object?>) $decoded]';
}

String _decodeRecord(_Json type, String known, int depth) {
  final map = 'map$depth';
  final fields = _list(type, 'fields').map((field) {
    final decoded = _decode(
      field['type']! as _Json,
      "$map['${field['name']}']",
      depth: depth + 1,
    );

    return '${field['name']}: $decoded';
  });

  return 'switch ($known as Map<String, Object?>) { final $map => (${fields.join(', ')}) }';
}

Future<String> _format(String source) async {
  final directory = await Directory.systemTemp.createTemp('canvist_generate');

  try {
    final file = File('${directory.path}/extensions.g.dart');
    await file.writeAsString(source);
    final result = await Process.run(Platform.resolvedExecutable, [
      'format',
      '--language-version=3.13',
      file.path,
    ]);

    if (result.exitCode != 0) {
      throw ProcessException(
        'dart',
        ['format'],
        '${result.stderr}',
        result.exitCode,
      );
    }

    return await file.readAsString();
  } finally {
    await directory.delete(recursive: true);
  }
}
