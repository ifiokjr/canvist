/**
 * Generate `src/extensions.generated.ts` from the extension metadata that
 * `canvist_extensions` snapshots in its tests, so the TypeScript types come
 * from the same metadata the Rust commands are checked against.
 *
 * Every extension comes from the full metadata snapshot; the StarterKit
 * snapshot says which of them make up `starterKit`, the default set.
 *
 * Run with `node scripts/generate.ts` or `deno run -R -W scripts/generate.ts`.
 * Pass `--check` to fail instead of writing when the file is out of date.
 *
 * @module
 */
import { readFileSync, writeFileSync } from "node:fs";

const snapshots = "../../../crates/canvist_extensions/tests/snapshots/";
const everySnapshot = new URL(
	`${snapshots}extensions_api__extension_metadata.snap`,
	import.meta.url,
);
const starterKitSnapshot = new URL(
	`${snapshots}api__starter_kit_metadata.snap`,
	import.meta.url,
);
const output = new URL("../src/extensions.generated.ts", import.meta.url);

/** Extensions every engine registers, so TypeScript lists them for you. */
const CORE = ["doc", "paragraph", "baseKeymap", "undoInputRule"];

interface Described {
	readonly name: string;
}

/** The JSON body of an insta snapshot: everything after its header. */
function snapshotBody(text: string): string {
	const header = /^---\n[\s\S]*?\n---\n/;
	return text.replace(header, "");
}

function render(
	extensions: readonly Described[],
	starterKitNames: readonly string[],
): string {
	const core = extensions.filter((extension) => CORE.includes(extension.name));
	const named = (name: string) =>
		extensions.find((extension) => extension.name === name);
	const starterKit = starterKitNames
		.filter((name) => !CORE.includes(name))
		.map(named)
		.filter((extension) => extension !== undefined);
	const optional = extensions.filter((extension) =>
		!CORE.includes(extension.name)
	);
	const declarations = extensions.map((extension) =>
		`/** The \`${extension.name}\` extension. */\nexport const ${extension.name} = ${
			JSON.stringify(extension, null, "\t")
		} as const satisfies ExtensionDescriptor;\n`
	);
	const list = (items: readonly Described[]) =>
		items.map((item) => item.name).join(", ");

	return [
		"// Generated by scripts/generate.ts from canvist_extensions' metadata snapshots. Do not edit.\n",
		'import type { ExtensionDescriptor } from "./types.ts";\n',
		...declarations,
		"/** The extensions every engine registers. */",
		`export const core = [${list(core)}] as const;\n`,
		"/** Every optional StarterKit extension, the default for `createEngine`. */",
		`export const starterKit = [${list(starterKit)}] as const;\n`,
		"/** Every optional extension canvist ships, the StarterKit's included. */",
		`export const allExtensions = [${list(optional)}] as const;\n`,
	].join("\n");
}

function read(snapshot: URL): readonly Described[] {
	return JSON.parse(snapshotBody(readFileSync(snapshot, "utf8")));
}

const generated = render(
	read(everySnapshot),
	read(starterKitSnapshot).map((extension) => extension.name),
);

if (process.argv.includes("--check")) {
	if (readFileSync(output, "utf8") !== generated) {
		console.error(
			"src/extensions.generated.ts is out of date; run scripts/generate.ts",
		);
		process.exit(1);
	}
} else {
	writeFileSync(output, generated);
}
